    #[test]
    fn water_in_waterlogged_blocks() {
        let (stone, seagrass) = (1, 2370); // Java 26.3 state ids
        assert!(waterlogged(seagrass) && !waterlogged(stone));
        assert_eq!((liquid_layer(seagrass), liquid_layer(stone)), (java_block(JAVA_WATER), java_block(0)));
        // A chunk whose y 0..15 section is all seagrass: that sub-chunk has two block storages, the others one.
        // Each section: counts, single-value blocks (bits 0, the state), single-value biomes.
        let sections: Vec<u8> = (0..24u32)
            .flat_map(|s| {
                let mut v = vec![0, 0, 0, 0, 0];
                uvarint(&mut v, if s == 4 { seagrass } else { 0 });
                v.extend([0, 0]);
                v
            })
            .collect();
        let (_, payload) = java_chunk_to_bedrock(&sections, 0, 0, &[]).unwrap();
        assert_eq!(payload[..3], [9, 1, (-4i8) as u8], "the lowest sub-chunk: one storage");
        let fourth = payload.windows(3).position(|w| w == [9, 2, 0]);
        assert!(fourth.is_some(), "the seagrass sub-chunk (y index 0) has two storages");
    }

