//! Bedrock chunk encoding (network format), currently for a generated flat test world.
//! Formats from dragonfly (MIT): server/world/chunk/encode.go and server/world/network_block_hash.go.

/// Network id of a block state when StartGame says "block network ids are hashes":
/// FNV-1a 32 over little-endian NBT `{name: <name>, states: {}}`.
/// shortcut: only blocks without state properties; real terrain needs sorted states encoded too.
pub fn block_hash(name: &str) -> u32 {
    let mut d = vec![10, 0, 0, 8];
    for s in ["name", name] {
        d.extend((s.len() as u16).to_le_bytes());
        d.extend(s.as_bytes());
    }
    d.push(10);
    d.extend(6u16.to_le_bytes());
    d.extend(b"states");
    d.extend([0, 0]); // end of states, end of root
    d.iter().fold(0x811c9dc5u32, |h, &b| (h ^ b as u32).wrapping_mul(0x01000193))
}

/// Overworld sub-chunks span y = -64..320, i.e. indices -4..=19.
const OVERWORLD_SUBCHUNKS: usize = 24;
const PLAINS: i32 = 1;

/// LevelChunk payload for a flat world: stone up to y=47, dirt to y=62, grass on top at y=63, air above.
/// Returns (sub-chunk count, payload).
pub fn flat_chunk() -> (u32, Vec<u8>) {
    let mut p = Vec::new();
    let stone = block_hash("minecraft:stone");
    for y in -4i8..=2 {
        p.extend([9, 1, y as u8, 0 << 1 | 1]); // version 9, one storage, y index, 0 bits per block (network)
        varint(&mut p, stone as i32); // single-entry palette: no length prefix
    }
    // y = 48..63: dirt, with grass_block where the in-sub-chunk y is 15.
    p.extend([9, 1, 3, 1 << 1 | 1]); // 1 bit per block
    for _ in 0..128 {
        // Index = x<<8 | z<<4 | y, 32 per word, so y=15 is bits 15 and 31 of every word.
        p.extend(0x8000_8000u32.to_le_bytes());
    }
    varint(&mut p, 2);
    varint(&mut p, block_hash("minecraft:dirt") as i32);
    varint(&mut p, block_hash("minecraft:grass_block") as i32);
    // Air above, up to the build limit: the client treats a missing sub-chunk as unloaded and freezes the
    // player's physics (and its loading screen) while the player stands in one.
    let air = block_hash("minecraft:air");
    for y in 4i8..=19 {
        p.extend([9, 1, y as u8, 1]);
        varint(&mut p, air as i32);
    }
    for _ in 0..OVERWORLD_SUBCHUNKS {
        p.push(0 << 1 | 1); // biome storage: single value
        varint(&mut p, PLAINS);
    }
    p.push(0); // no border blocks
    (OVERWORLD_SUBCHUNKS as u32, p)
}

/// Bedrock network hash for each Java block state id, generated by tools/gen_block_table.py from
/// GeyserMC/mappings (MIT, see data/README.md) for Java 26.3.
static JAVA_BLOCKS: &[u8] = include_bytes!("../data/java_blocks.bin");

pub fn java_block(state: u32) -> u32 {
    let i = state as usize * 4;
    match JAVA_BLOCKS.get(i..i + 4) {
        Some(b) => u32::from_le_bytes(b.try_into().unwrap()),
        None => block_hash("minecraft:air"), // unknown state (newer Java version than the table)
    }
}

/// Converts the section data of a Java 26.3 chunk packet (24 overworld sections, y = -64..320) into a Bedrock
/// LevelChunk payload. Returns (sub-chunk count, payload).
/// shortcut: every biome becomes plains; real biomes need the Java biome registry mapped to Bedrock ids.
pub fn java_chunk_to_bedrock(mut data: &[u8]) -> Result<(u32, Vec<u8>), String> {
    let mut p = Vec::new();
    for section in 0..OVERWORLD_SUBCHUNKS {
        take(&mut data, 4)?; // block count, fluid count (i16 each)
        let java = read_paletted(&mut data, 4096, 8)?; // index y<<8 | z<<4 | x
        read_paletted(&mut data, 64, 3)?; // biomes, unused for now
        let mut bedrock = [0u32; 4096]; // index x<<8 | z<<4 | y
        for (j, &state) in java.iter().enumerate() {
            let (y, z, x) = (j >> 8, (j >> 4) & 15, j & 15);
            bedrock[x << 8 | z << 4 | y] = java_block(state);
        }
        write_subchunk(&mut p, section as i8 - 4, &bedrock);
    }
    for _ in 0..OVERWORLD_SUBCHUNKS {
        p.push(1);
        varint(&mut p, PLAINS);
    }
    p.push(0); // no border blocks
    Ok((OVERWORLD_SUBCHUNKS as u32, p))
}

fn take<'a>(r: &mut &'a [u8], n: usize) -> Result<&'a [u8], String> {
    let head = r.get(..n).ok_or("truncated Java chunk")?;
    *r = &r[n..];
    Ok(head)
}

fn read_uvarint(r: &mut &[u8]) -> Result<u32, String> {
    let mut v = 0u32;
    for i in 0..5 {
        let b = take(r, 1)?[0];
        v |= ((b & 0x7F) as u32) << (7 * i);
        if b & 0x80 == 0 {
            return Ok(v);
        }
    }
    Err("varint too long".into())
}

/// Java paletted container: `[u8 bits]`, then one value (bits 0), a palette (bits <= max_palette_bits)
/// or global ids, then a fixed-size long[] with `64 / bits` entries per long, low bits first.
fn read_paletted(r: &mut &[u8], entries: usize, max_palette_bits: u8) -> Result<Vec<u32>, String> {
    let bits = take(r, 1)?[0];
    if bits == 0 {
        return Ok(vec![read_uvarint(r)?; entries]);
    }
    if bits > 32 {
        return Err(format!("bad bits per entry {bits}"));
    }
    let palette = if bits <= max_palette_bits {
        let n = read_uvarint(r)? as usize;
        (0..n).map(|_| read_uvarint(r)).collect::<Result<Vec<_>, _>>()?
    } else {
        Vec::new() // global palette: values are ids
    };
    let per_long = 64 / bits as usize;
    let longs = take(r, entries.div_ceil(per_long) * 8)?;
    let mask = (1u64 << bits) - 1;
    (0..entries)
        .map(|i| {
            let word = u64::from_be_bytes(longs[i / per_long * 8..][..8].try_into().unwrap());
            let v = ((word >> (i % per_long * bits as usize)) & mask) as usize;
            if palette.is_empty() { Ok(v as u32) } else { palette.get(v).copied().ok_or("palette index out of range".into()) }
        })
        .collect()
}

/// Bedrock sub-chunk (version 9, one storage) with the smallest palette that fits; words never span entries.
fn write_subchunk(p: &mut Vec<u8>, y_index: i8, blocks: &[u32; 4096]) {
    let mut palette: Vec<u32> = Vec::new();
    let indices: Vec<usize> = blocks
        .iter()
        .map(|b| palette.iter().position(|x| x == b).unwrap_or_else(|| {
            palette.push(*b);
            palette.len() - 1
        }))
        .collect();
    p.extend([9, 1, y_index as u8]);
    if palette.len() == 1 {
        p.push(1); // 0 bits per block (network flag set)
        varint(p, palette[0] as i32);
        return;
    }
    let bits = [1usize, 2, 3, 4, 5, 6, 8, 16].into_iter().find(|b| 1 << b >= palette.len()).unwrap();
    p.push((bits << 1 | 1) as u8);
    let per_word = 32 / bits;
    for chunk in indices.chunks(per_word) {
        let word = chunk.iter().enumerate().fold(0u32, |w, (k, &i)| w | (i as u32) << (k * bits));
        p.extend(word.to_le_bytes());
    }
    varint(p, palette.len() as i32);
    for b in &palette {
        varint(p, *b as i32);
    }
}

fn varint(out: &mut Vec<u8>, v: i32) {
    let mut u = ((v << 1) ^ (v >> 31)) as u32;
    while u >= 0x80 {
        out.push(u as u8 | 0x80);
        u >>= 7;
    }
    out.push(u as u8);
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fnv_and_hash_shape() {
        // FNV-1a 32 reference vector: "a" -> 0xe40c292c.
        assert_eq!(b"a".iter().fold(0x811c9dc5u32, |h, &b| (h ^ b as u32).wrapping_mul(0x01000193)), 0xe40c292c);
        assert_ne!(block_hash("minecraft:air"), block_hash("minecraft:stone"));
    }

    #[test]
    fn java_table_matches_rust_hash() {
        assert_eq!(java_block(0), block_hash("minecraft:air"), "Java state 0 is air");
        assert_eq!(java_block(1), block_hash("minecraft:stone"), "Python generator and Rust hash agree");
        assert_eq!(java_block(u32::MAX), block_hash("minecraft:air"));
    }

    /// One Java section: blocks as a 4-bit palette [air, stone] with stone only at y=0, biome single value.
    fn java_section(out: &mut Vec<u8>, stone_floor: bool) {
        out.extend([0, 0, 0, 0]); // block count, fluid count
        if stone_floor {
            out.extend([4, 2, 0, 1]); // 4 bits, palette [air(0), stone(1)]
            for l in 0..256 {
                // 16 entries per long; java index y<<8|z<<4|x, so the first 256 entries (16 longs) are y = 0
                out.extend(if l < 16 { 0x1111_1111_1111_1111u64 } else { 0 }.to_be_bytes());
            }
        } else {
            out.extend([0, 0]); // single value: air
        }
        out.extend([0, 0]); // biomes: single value
    }

    #[test]
    fn translates_java_chunk() {
        let mut data = Vec::new();
        for s in 0..24 {
            java_section(&mut data, s == 8); // section 8 = y 64..79
        }
        let (count, p) = java_chunk_to_bedrock(&data).unwrap();
        assert_eq!(count, 24);
        let air = block_hash("minecraft:air");
        assert_eq!(&p[..4], &[9, 1, 0xFC, 1][..], "air section: single-value storage");
        let mut first = Vec::new();
        varint(&mut first, air as i32);
        assert_eq!(&p[4..4 + first.len()], &first[..]);
        // Section 8 (y index 4): 1-bit palette [stone, air]; bedrock index x<<8|z<<4|y, so y=0 is bit 0 of
        // every 16-bit group: each word = 0b...0001_0000_0000_0000_0001 inverted (stone=0, air=1).
        let at = p.windows(4).position(|w| w == [9, 1, 4, 3]).expect("1-bit section at y index 4");
        assert_eq!(u32::from_le_bytes(p[at + 4..at + 8].try_into().unwrap()), 0xFFFE_FFFE);
        assert!(java_chunk_to_bedrock(&data[..10]).is_err(), "truncated data is an error, not a panic");
    }

    #[test]
    fn flat_chunk_layout() {
        let (count, p) = flat_chunk();
        assert_eq!(count, 24, "every overworld sub-chunk, including the air the player stands in");
        assert!(p.windows(3).any(|w| w == [9, 1, 19]), "top sub-chunk (y index 19) present");
        assert_eq!(&p[..4], &[9, 1, 0xFC, 1][..], "first sub-chunk is y index -4, single-value storage");
        let top = p.windows(4).position(|w| w == [9, 1, 3, 3]).expect("1-bit top sub-chunk");
        assert_eq!(&p[top + 4..top + 8], &[0x00, 0x80, 0x00, 0x80][..]);
        assert_eq!(*p.last().unwrap(), 0, "border block count");
    }
}
