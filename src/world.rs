static JAVA_WATERLOGGED: &[u8] = include_bytes!("../data/java_waterlogged.bin");
/// Java 26.3's still water (`minecraft:water`, level 0).
const JAVA_WATER: u32 = 89;

/// Whether a Java state holds water (waterlogged, or seagrass and kelp): Bedrock draws it as a second block layer.
pub fn waterlogged(state: u32) -> bool {
    JAVA_WATERLOGGED.get(state as usize / 8).is_some_and(|b| b >> (state % 8) & 1 != 0)
}

/// The Bedrock block for a Java state's second layer: still water if it holds water, else air.
pub fn liquid_layer(state: u32) -> u32 {
    java_block(if waterlogged(state) { JAVA_WATER } else { 0 })
}

static JAVA_DIG: &[u8] = include_bytes!("../data/java_dig.bin");
static JAVA_TOOLS: &str = include_str!("../data/java_tools.txt");

/// Ticks Java takes to mine a block state holding an item (Java 26.3's getDestroyProgress), or None when it
/// can't be mined. shortcut: haste, mining fatigue and being under water are left out; add them if cracks drift.
pub fn break_ticks(state: u32, item: Option<i32>, efficiency: u8, on_ground: bool) -> Option<u32> {
    let e = JAVA_DIG.get(state as usize * 6..)?.get(..6)?;
    let (hardness, mask) = (u16::from_le_bytes([e[0], e[1]]), u32::from_le_bytes([e[2], e[3], e[4], e[5]]));
    if hardness == 0xFFFF {
        return None;
    }
    // The item's tool rules: the first matching rule with a speed gives it, the first with correct-for-drops too.
    let id = item.map(|i| i.to_string());
    let line = JAVA_TOOLS.lines().find(|l| id.as_deref().is_some_and(|id| l.split(' ').next() == Some(id)));
    let mut words = line.unwrap_or("").split("  #").next().unwrap_or("").split(' ').skip(1);
    let mut speed: f32 = words.next().and_then(|s| s.parse().ok()).unwrap_or(1.0);
    let (mut rule_speed, mut correct) = (None, None);
    for rule in words {
        let mut p = rule.split(':');
        let (set, s, c) = (p.next().and_then(|s| s.parse::<u32>().ok()), p.next(), p.next());
        if set.is_some_and(|set| mask & 1 << set != 0) {
            rule_speed = rule_speed.or(s.and_then(|s| s.parse::<f32>().ok()));
            correct = correct.or(c.and_then(|c| c.parse::<u8>().ok()));
        }
    }
    speed = rule_speed.unwrap_or(speed);
    if speed > 1.0 && efficiency > 0 {
        speed += (efficiency as f32).powi(2) + 1.0;
    }
    if !on_ground {
        speed /= 5.0;
    }
    let harvest = mask >> 31 == 0 || correct == Some(1);
    let progress = speed / (hardness as f32 / 100.0) / if harvest { 30.0 } else { 100.0 };
    Some((1.0 / progress).ceil() as u32)
}

/// The Java block state at (x, z within the chunk, world y) in a chunk packet's section data.
pub fn java_state_at(mut data: &[u8], x: usize, y: i32, z: usize) -> Option<u32> {
    let section = (y + 64).div_euclid(16) as usize;
    for s in 0..OVERWORLD_SUBCHUNKS.min(section + 1) {
        take(&mut data, 4).ok()?;
        let blocks = read_paletted(&mut data, 4096, 8).ok()?;
        if s == section {
            return blocks.get(((y & 15) as usize) << 8 | z << 4 | x).copied();
        }
        read_paletted(&mut data, 64, 3).ok()?;
    }
    None
}

static JAVA_ITEMS: &[u8] = include_bytes!("../data/java_items.bin");

/// Bedrock item id, aux value and block network id (0 for non-block items) of a Java item.
pub fn java_item(id: i32) -> Option<(i16, u16, u32)> {
    let e = JAVA_ITEMS.get(usize::try_from(id).ok()? * 8..)?.get(..8)?;
    let state = u32::from_le_bytes(e[4..8].try_into().unwrap());
    let block = if state == u32::MAX { 0 } else { java_block(state) };
    Some((i16::from_le_bytes([e[0], e[1]]), u16::from_le_bytes([e[2], e[3]]), block))
}

/// Per creative item (creative net id - 1): the Java item id it gives, i32 LE, -1 when none (tools/gen_item_data.py).
static CREATIVE_JAVA: &[u8] = include_bytes!("../data/creative_java.bin");

/// The Java item a creative menu entry gives. shortcut: item NBT (potion types, enchanted books) isn't carried over.
pub fn creative_java(net_id: u32) -> Option<i32> {
    let i = (net_id as usize).checked_sub(1)? * 4;
    let id = i32::from_le_bytes(CREATIVE_JAVA.get(i..i + 4)?.try_into().unwrap());
    (id >= 0).then_some(id)
}

