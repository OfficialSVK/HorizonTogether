/// Java chest and trapped chest states: `state dx dz lead` per line (tools/gen_block_table.py).
static JAVA_CHESTS: &str = include_str!("../data/java_chests.txt");

/// For a Java chest state: the offset of its other half (0, 0 when single) and whether it leads on Bedrock.
fn chest(state: u32) -> Option<(i32, i32, bool)> {
    static TABLE: std::sync::OnceLock<std::collections::HashMap<u32, (i32, i32, bool)>> = std::sync::OnceLock::new();
    let table = TABLE.get_or_init(|| {
        JAVA_CHESTS
            .lines()
            .filter_map(|l| {
                let v: Vec<i32> = l.split_whitespace().filter_map(|n| n.parse().ok()).collect();
                Some((u32::try_from(*v.first()?).ok()?, (*v.get(1)?, *v.get(2)?, *v.get(3)? == 1)))
            })
            .collect()
    });
    table.get(&state).copied()
}

/// Bedrock block entity data (network NBT) for a chest: a double chest names its other half (and the right
/// half leads), as Geyser does, so Bedrock pairs the two the way Java does and shows its 54 slots in order.
pub fn chest_nbt(pos: [i32; 3], state: u32) -> Option<Vec<u8>> {
    let (dx, dz, lead) = chest(state)?;
    let mut n = NbtOut::block_entity("Chest", pos);
    n.byte("isMovable", 1);
    if (dx, dz) != (0, 0) {
        n.int("pairx", pos[0] + dx).int("pairz", pos[2] + dz);
        if lead {
            n.int("pairlead", 1);
        }
    }
    Some(n.end())
}

/// Bedrock sign data (as Geyser's SignBlockEntityTranslator): each side's lines joined by newlines.
/// shortcut: text colour (always black) and glowing text aren't carried over; add them from the Java NBT.
pub fn sign_nbt(pos: [i32; 3], hanging: bool, front: &str, back: &str) -> Vec<u8> {
    let mut n = NbtOut::block_entity(if hanging { "HangingSign" } else { "Sign" }, pos);
    for (side, text) in [("FrontText", front), ("BackText", back)] {
        n.compound(side).string("Text", text).int("SignTextColor", 0xFF00_0000u32 as i32).byte("IgnoreLighting", 0);
        n.0.push(0); // end of the side
    }
    n.byte("IsWaxed", 0).byte("isMovable", 1);
    n.end()
}

/// SyncActorProperty body for a mob with a climate variant (pig, cow, chicken): its properties as the official server
/// defines them, `minecraft:climate_variant` (index 0: temperate, warm, cold), then `minecraft:sound_variant`.
pub fn climate_properties(entity: &str, sounds: &[&str]) -> Vec<u8> {
    let mut n = NbtOut(vec![10, 0]);
    n.tag(9, "properties").0.push(10); // a list of compounds
    varint(&mut n.0, 2);
    for (name, values) in [("minecraft:climate_variant", &["temperate", "warm", "cold"][..]), ("minecraft:sound_variant", sounds)] {
        n.tag(9, "enum").0.push(8); // a list of strings
        varint(&mut n.0, values.len() as i32);
        for v in values {
            uvarint(&mut n.0, v.len() as u32);
            n.0.extend(v.as_bytes());
        }
        n.string("name", name).int("type", 3).0.push(0); // type 3: enum
    }
    n.string("type", entity);
    n.end()
}

/// Writer for a Bedrock network NBT compound (little-endian; varint lengths and ints).
struct NbtOut(Vec<u8>);

impl NbtOut {
    /// A block entity: id and position.
    fn block_entity(id: &str, pos: [i32; 3]) -> Self {
        let mut n = NbtOut(vec![10, 0]); // root compound, empty name
        n.string("id", id).int("x", pos[0]).int("y", pos[1]).int("z", pos[2]);
        n
    }
    fn tag(&mut self, kind: u8, name: &str) -> &mut Self {
        self.0.push(kind);
        uvarint(&mut self.0, name.len() as u32);
        self.0.extend(name.as_bytes());
        self
    }
    fn string(&mut self, name: &str, v: &str) -> &mut Self {
        self.tag(8, name);
        uvarint(&mut self.0, v.len() as u32);
        self.0.extend(v.as_bytes());
        self
    }
    fn int(&mut self, name: &str, v: i32) -> &mut Self {
        self.tag(3, name);
        varint(&mut self.0, v);
        self
    }
    fn byte(&mut self, name: &str, v: u8) -> &mut Self {
        self.tag(1, name);
        self.0.push(v);
        self
    }
    fn compound(&mut self, name: &str) -> &mut Self {
        self.tag(10, name)
    }
    fn end(mut self) -> Vec<u8> {
        self.0.push(0);
        self.0
    }
}

/// The text of one side of a Bedrock sign, from the client's block entity data (network NBT): the `Text` of
/// its `FrontText` or `BackText` compound.
pub fn bedrock_sign_text(mut nbt: &[u8], front: bool) -> Option<String> {
    let want = if front { "FrontText" } else { "BackText" };
    let r = &mut nbt;
    if take(r, 1).ok()?[0] != 10 {
        return None;
    }
    skip_string(r)?; // root name
    let mut found = None;
    walk_compound(r, &mut |path: &str, name: &str, value: &str| {
        if path == want && name == "Text" {
            found = Some(value.to_string());
        }
    }, "")?;
    found
}

fn skip_string(r: &mut &[u8]) -> Option<()> {
    let n = read_uvarint(r).ok()? as usize;
    take(r, n).ok().map(|_| ())
}

/// Reads a network NBT compound's entries, calling `seen(compound name, entry name, value)` for strings.
fn walk_compound(r: &mut &[u8], seen: &mut dyn FnMut(&str, &str, &str), path: &str) -> Option<()> {
    loop {
        let kind = take(r, 1).ok()?[0];
        if kind == 0 {
            return Some(());
        }
        let n = read_uvarint(r).ok()? as usize;
        let name = String::from_utf8_lossy(take(r, n).ok()?).into_owned();
        walk_payload(r, kind, seen, &name, path)?;
    }
}

fn walk_payload(r: &mut &[u8], kind: u8, seen: &mut dyn FnMut(&str, &str, &str), name: &str, path: &str) -> Option<()> {
    match kind {
        1 => drop(take(r, 1).ok()?),
        2 => drop(take(r, 2).ok()?),
        3 | 4 => drop(read_uvarint64(r)?),
        5 => drop(take(r, 4).ok()?),
        6 => drop(take(r, 8).ok()?),
        7 => {
            let n = read_uvarint(r).ok()? >> 1; // zigzag length
            take(r, n as usize).ok()?;
        }
        8 => {
            let n = read_uvarint(r).ok()? as usize;
            let v = String::from_utf8_lossy(take(r, n).ok()?).into_owned();
            seen(path, name, &v);
        }
        9 => {
            let elem = take(r, 1).ok()?[0];
            for _ in 0..read_uvarint(r).ok()? >> 1 {
                walk_payload(r, elem, seen, name, path)?;
            }
        }
        10 => walk_compound(r, seen, name)?,
        11 | 12 => {
            for _ in 0..read_uvarint(r).ok()? >> 1 {
                read_uvarint64(r)?;
            }
        }
        _ => return None,
    }
    Some(())
}

fn read_uvarint64(r: &mut &[u8]) -> Option<u64> {
    let mut v = 0u64;
    for i in 0..10 {
        let b = take(r, 1).ok()?[0];
        v |= ((b & 0x7F) as u64) << (7 * i);
        if b & 0x80 == 0 {
            return Some(v);
        }
    }
    None
}

/// Converts the section data of a Java 26.3 chunk packet (24 overworld sections, y = -64..320) into a Bedrock
/// LevelChunk payload. Returns (sub-chunk count, payload).
/// shortcut: every biome becomes plains; real biomes need the Java biome registry mapped to Bedrock ids.
/// Chunk `cx, cz`: its chests' block entity data follows the payload, so Bedrock pairs double chests on load.
/// `biomes` gives the Bedrock biome id of each Java biome id (Event::Biomes); unknown ones are plains.
pub fn java_chunk_to_bedrock(mut data: &[u8], cx: i32, cz: i32, biomes: &[u32]) -> Result<(u32, Vec<u8>), String> {
    let mut p = Vec::new();
    let mut entities = Vec::new();
    let mut biome_storage = Vec::new();
    for section in 0..OVERWORLD_SUBCHUNKS {
        take(&mut data, 4)?; // block count, fluid count (i16 each)
        let java = read_paletted(&mut data, 4096, 8)?; // index y<<8 | z<<4 | x
        // Biomes: 4x4x4 cells (index y<<4 | z<<2 | x); Bedrock has one per block, in its block order.
        let cells = read_paletted(&mut data, 64, 3)?;
        let mut biome = [0u32; 4096];
        for (i, b) in biome.iter_mut().enumerate() {
            let (x, z, y) = (i >> 8, (i >> 4) & 15, i & 15);
            let java_biome = cells[(y >> 2) << 4 | (z >> 2) << 2 | (x >> 2)];
            *b = biomes.get(java_biome as usize).copied().unwrap_or(PLAINS as u32);
        }
        write_storage(&mut biome_storage, &biome);
        let mut bedrock = [0u32; 4096]; // index x<<8 | z<<4 | y
        let mut liquid = [java_block(0); 4096]; // the second layer: water in waterlogged blocks, else air
        let mut wet = false;
        for (j, &state) in java.iter().enumerate() {
            let (y, z, x) = (j >> 8, (j >> 4) & 15, j & 15);
            bedrock[x << 8 | z << 4 | y] = java_block(state);
            if waterlogged(state) {
                liquid[x << 8 | z << 4 | y] = liquid_layer(state);
                wet = true;
            }
            if chest(state).is_some() {
                let pos = [cx * 16 + x as i32, (section as i32 - 4) * 16 + y as i32, cz * 16 + z as i32];
                entities.extend(chest_nbt(pos, state).unwrap_or_default());
            }
        }
        write_subchunk(&mut p, section as i8 - 4, &bedrock, wet.then_some(&liquid));
    }
    p.extend(biome_storage); // one biome storage per sub-chunk
    p.push(0); // no border blocks
    p.extend(entities); // block entities: network NBT compounds, one after another
    Ok((OVERWORLD_SUBCHUNKS as u32, p))
}

fn take<'a>(r: &mut &'a [u8], n: usize) -> Result<&'a [u8], String> {
    let head = r.get(..n).ok_or("truncated Java chunk")?;
    *r = &r[n..];
    Ok(head)
}

fn read_uvarint(r: &mut &[u8]) -> Result<u32, String> {
    let mut v = 0u32;
    for i in 0..5 {
        let b = take(r, 1)?[0];
        v |= ((b & 0x7F) as u32) << (7 * i);
        if b & 0x80 == 0 {
            return Ok(v);
        }
    }
    Err("varint too long".into())
}

/// Java paletted container: `[u8 bits]`, then one value (bits 0), a palette (bits <= max_palette_bits)
/// or global ids, then a fixed-size long[] with `64 / bits` entries per long, low bits first.
fn read_paletted(r: &mut &[u8], entries: usize, max_palette_bits: u8) -> Result<Vec<u32>, String> {
    let bits = take(r, 1)?[0];
    if bits == 0 {
        return Ok(vec![read_uvarint(r)?; entries]);
    }
    if bits > 32 {
        return Err(format!("bad bits per entry {bits}"));
    }
    let palette = if bits <= max_palette_bits {
        let n = read_uvarint(r)? as usize;
        (0..n).map(|_| read_uvarint(r)).collect::<Result<Vec<_>, _>>()?
    } else {
        Vec::new() // global palette: values are ids
    };
    let per_long = 64 / bits as usize;
    let longs = take(r, entries.div_ceil(per_long) * 8)?;
    let mask = (1u64 << bits) - 1;
    (0..entries)
        .map(|i| {
            let word = u64::from_be_bytes(longs[i / per_long * 8..][..8].try_into().unwrap());
            let v = ((word >> (i % per_long * bits as usize)) & mask) as usize;
            if palette.is_empty() { Ok(v as u32) } else { palette.get(v).copied().ok_or("palette index out of range".into()) }
        })
        .collect()
}

/// Bedrock sub-chunk (version 9): one block storage, or two when some blocks hold water (the second layer).
fn write_subchunk(p: &mut Vec<u8>, y_index: i8, blocks: &[u32; 4096], liquid: Option<&[u32; 4096]>) {
    p.extend([9, 1 + liquid.is_some() as u8, y_index as u8]);
    write_storage(p, blocks);
    if let Some(liquid) = liquid {
        write_storage(p, liquid);
    }
}

/// A paletted storage (blocks or biomes) with the smallest palette that fits; words never span entries.
fn write_storage(p: &mut Vec<u8>, blocks: &[u32; 4096]) {
    let mut palette: Vec<u32> = Vec::new();
    let indices: Vec<usize> = blocks
        .iter()
        .map(|b| palette.iter().position(|x| x == b).unwrap_or_else(|| {
            palette.push(*b);
            palette.len() - 1
        }))
        .collect();
    if palette.len() == 1 {
        p.push(1); // 0 bits per block (network flag set)
        varint(p, palette[0] as i32);
        return;
    }
    let bits = [1usize, 2, 3, 4, 5, 6, 8, 16].into_iter().find(|b| 1 << b >= palette.len()).unwrap();
    p.push((bits << 1 | 1) as u8);
    let per_word = 32 / bits;
    for chunk in indices.chunks(per_word) {
        let word = chunk.iter().enumerate().fold(0u32, |w, (k, &i)| w | (i as u32) << (k * bits));
        p.extend(word.to_le_bytes());
    }
    varint(p, palette.len() as i32);
    for b in &palette {
        varint(p, *b as i32);
    }
}

fn uvarint(out: &mut Vec<u8>, mut v: u32) {
    while v >= 0x80 {
        out.push(v as u8 | 0x80);
        v >>= 7;
    }
    out.push(v as u8);
}

fn varint(out: &mut Vec<u8>, v: i32) {
    let mut u = ((v << 1) ^ (v >> 31)) as u32;
    while u >= 0x80 {
        out.push(u as u8 | 0x80);
        u >>= 7;
    }
    out.push(u as u8);
}

